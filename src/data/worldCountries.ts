/**
 * Obtiene las ciudades dinámicas para cualquier código de país.
 * Si el país está en el catálogo, devuelve sus ciudades principales;
 * de lo contrario, devuelve opciones estándar regionales.
 */
export function getCitiesForCountry(countryCode: string): string[] {
  const country = WORLD_192_COUNTRIES.find(
    (c) => c.code.toUpperCase() === (countryCode || '').toUpperCase()
  );
  if (country && country.cities && country.cities.length > 0) {
    return country.cities;
  }
  return [
    'Capital Nacional',
    'Área Metropolitana Principal',
    'Región Central',
    'Zona Norte',
    'Zona Sur',
    'Distrito Financiero',
  ];
}
